"""Pre-design attribution for CANON (docs/canon_design.md section 8). Uses TRAIN and VALIDATION blocks only.

Run from the repo root:  .venv/Scripts/python scripts/canon_attribution.py
Naive detector (classical train block, classical validation threshold), benign validation flows of the 17 other
profiles, FPR with all V_FLOW features, leaving one feature group out, and with one group only. Rule (fixed in the
design before this ran): a group is a DRIVER if, for RF or AE, (all - leave-one-out) >= 0.10 or (only-group) >= 0.25.
Writes results/canon_attribution.csv and docs/canon_attribution.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

from pqdl import detectors as dt
from pqdl.canon import CLASSICAL_CONTEXT, GROUPS, group_features, handshake_delta
from pqdl.loaders import assert_single_source

ROOT = Path(__file__).resolve().parents[1]
SEEDS = (11, 12, 13, 14, 15)
DROP_MIN, ONLY_MIN = 0.10, 0.25


def fpr_by_profile(df: pd.DataFrame, cols: list[str], det: str) -> pd.Series:
    """Seed-mean FPR on benign validation flows of every non-classical profile."""
    tr, va = df[(df.block == "train") & (df.profile == CLASSICAL_CONTEXT)], df[(df.block == "val") & (df.profile == CLASSICAL_CONTEXT)]
    dom = dt.fit_domain(det, cols, tr, va, SEEDS)
    out = {}
    for profile, g in df[(df.block == "val") & ~df.attack & (df.profile != CLASSICAL_CONTEXT)].groupby("profile"):
        flags = dom.score(dt.design_matrix(g, cols)) > dom.thresholds[:, None]
        out[profile] = float(flags.mean())
    return pd.Series(out)


def main() -> int:
    df = pd.read_csv(ROOT / "data/flows/lab_flows.csv")
    assert_single_source(df)
    df = dt.time_block_split(dt.add_labels(df))
    assert set(df.loc[df.block == "test", "block"]) == {"test"}      # test rows exist but are never read below
    df = df[df.block != "test"]
    rows = []
    for det in ("rf", "ae", "iforest"):
        full = fpr_by_profile(df, list(dt.V_FLOW), det)
        rows.append({"detector": det, "variant": "all", "group": "-", "median_fpr": full.median()})
        for g in GROUPS:
            rest = [f for f in dt.V_FLOW if f not in group_features([g])]
            rows.append({"detector": det, "variant": "leave_out", "group": g,
                         "median_fpr": fpr_by_profile(df, rest, det).median()})
            rows.append({"detector": det, "variant": "only", "group": g,
                         "median_fpr": fpr_by_profile(df, group_features([g]), det).median()})
        print(f"  {det} done", flush=True)
    t = pd.DataFrame(rows)
    verdicts = []
    for g in GROUPS:
        reasons = []
        for det in ("rf", "ae"):
            sub = t[t.detector == det].set_index(["variant", "group"])["median_fpr"]
            drop = sub[("all", "-")] - sub[("leave_out", g)]
            only = sub[("only", g)]
            if drop >= DROP_MIN:
                reasons.append(f"{det}: leaving out lowers FPR by {drop:.3f}")
            if only >= ONLY_MIN:
                reasons.append(f"{det}: group alone gives FPR {only:.3f}")
        verdicts.append({"group": g, "driver": bool(reasons), "reasons": "; ".join(reasons) or "no"})
    v = pd.DataFrame(verdicts)
    # descriptive: observed vs model-predicted delta of per-profile benign validation medians
    med = df[(df.block == "val") & ~df.attack].groupby("profile")[["flow_s2c_bytes", "flow_c2s_bytes", "flow_s2c_pkts", "flow_c2s_pkts"]].median()
    ref = med.loc[CLASSICAL_CONTEXT]
    dd = []
    for profile in med.index:
        d, pred = med.loc[profile] - ref, handshake_delta(profile)
        dd.append({"profile": profile,
                   "s2c_bytes_obs": d.flow_s2c_bytes, "s2c_bytes_model": pred.s2c_bytes,
                   "c2s_bytes_obs": d.flow_c2s_bytes, "c2s_bytes_model": pred.c2s_bytes,
                   "s2c_pkts_obs": d.flow_s2c_pkts, "s2c_pkts_model": pred.s2c_pkts,
                   "c2s_pkts_obs": d.flow_c2s_pkts, "c2s_pkts_model": pred.c2s_pkts})
    dd = pd.DataFrame(dd)
    (ROOT / "results").mkdir(exist_ok=True)
    t.to_csv(ROOT / "results/canon_attribution.csv", index=False)
    pd.set_option("display.width", 220, "display.max_columns", 30, "display.float_format", "{:.3f}".format)
    wide = t.pivot_table(index=["variant", "group"], columns="detector", values="median_fpr")
    print(wide.to_string()); print(); print(v.to_string(index=False)); print(); print(dd.to_string(index=False))
    drivers = [r.group for r in v.itertuples() if r.driver]
    md = ["# CANON attribution (train/validation blocks only; generated by scripts/canon_attribution.py)", "",
          f"Rule (pre-registered): driver if RF or AE has (all - leave-one-out) >= {DROP_MIN} or (group only) >= {ONLY_MIN}.",
          "Statistic: median over the 17 non-classical profiles of the naive detector's FPR on benign validation flows.", "",
          "| variant | group | " + " | ".join(wide.columns) + " |", "|---|---|" + "---|" * len(wide.columns)]
    for (variant, g), r in wide.iterrows():
        md.append(f"| {variant} | {g} | " + " | ".join(f"{r[c]:.3f}" for c in wide.columns) + " |")
    md += ["", "| group | driver | reason |", "|---|---|---|"] + [f"| {r.group} | {r.driver} | {r.reasons} |" for r in v.itertuples()]
    md += ["", f"**Drivers: {', '.join(drivers) or 'none'}**", "",
           "Observed vs model-predicted delta (benign validation medians, relative to the classical profile):", "",
           "```", dd.round(1).to_string(index=False), "```"]
    (ROOT / "docs/canon_attribution.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\nDRIVERS:", drivers)
    return 0


if __name__ == "__main__":
    sys.exit(main())
